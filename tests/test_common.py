class ManuscriptCheckTest(unittest.TestCase):
    def test_prose_numbers_ignore_markup_comments_and_small_counts(self) -> None:
        text = ("Success falls from 824/1,400 (58.86\\%) % 999 is a comment\n"
                "\\label{tab:x1234} \\cite{ref2027} across 14 tasks")
        self.assertEqual(check_build.numbers(text), Counter({"824": 1, "1400": 1, "58.86": 1}))

    def test_every_table_states_its_provenance(self) -> None:
        for path in sorted(common.TABLES.glob("*.tex")):
            first_line = path.read_text(encoding="utf-8").splitlines()[0]
            with self.subTest(table=path.name):
                self.assertTrue(first_line.startswith(TABLE_HEADERS), first_line)

    def test_submission_checks_detect_citation_appendix_and_disclosure_errors(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for document, folder in (("main", "sections"), ("manuscript_zh", "zh/sections")):
                (root / folder).mkdir(parents=True)
                (root / folder / "llm_usage.tex").write_text(
                    r"\section*{LLM Usage Statement}", encoding="utf-8")
                (root / f"{document}.tex").write_text(
                    rf"\input{{{folder}/conclusion}}\input{{{folder}/llm_usage}}"
                    r"\bibliography{references}", encoding="utf-8")
            for document in check_build.DOCUMENTS:
                aux = r"\citation{example}\bibcite{example}{{1}{2027}{{Author}}{{}}}"
                if document != "supplementary":
                    aux += r"\newlabel{sec:llm_usage}{{}{9}}"
                if document != "main":
                    aux += "".join(rf"\newlabel{{app:{name}}}{{{{{letter}}}{{1}}}}"
                                   for name, letter in zip(check_build.APPENDICES, "ABCDEFGH"))
                (root / f"{document}.aux").write_text(aux, encoding="utf-8")
                (root / f"{document}.blg").write_text("BibTeX finished", encoding="utf-8")
                (root / f"{document}.pdf").touch()
            with mock.patch.object(check_build, "REPO", root):
                self.assertEqual(check_build.submission_findings(), [])
                path = root / "main.aux"
                path.write_text(path.read_text() + r"\citation{missing}", encoding="utf-8")
                self.assertTrue(any("missing ['missing']" in item
                                    for item in check_build.submission_findings()))
                path = root / "supplementary.aux"
                path.write_text(path.read_text().replace(
                    r"\newlabel{app:implementation}{{A}", r"\newlabel{app:implementation}{{B}"),
                    encoding="utf-8")
                self.assertTrue(any("appendix A (implementation)" in item
                                    for item in check_build.submission_findings()))
                path = root / "main.tex"
                path.write_text(path.read_text().replace(
                    r"\input{sections/llm_usage}", ""), encoding="utf-8")
                self.assertTrue(any("must follow the body" in item
                                    for item in check_build.submission_findings()))

    def test_file_line_errors_are_blocking(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "main.log").write_text(
                "./table.tex:19: Forbidden control sequence found while scanning.\n"
                "Missing character: There is no x in font nullfont!\n", encoding="utf-8")
            with mock.patch.object(check_build, "REPO", root):
                findings = check_build.log_findings("main")
                self.assertEqual(len(findings["errors"]), 1)
                self.assertEqual(len(findings["missing_glyphs"]), 1)
                self.assertIn("missing_glyphs", check_build.BLOCKING)


