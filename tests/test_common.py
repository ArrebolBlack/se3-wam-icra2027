class PdfMetadataTest(unittest.TestCase):
    def test_pdf_metadata_timestamps_are_reproducible(self) -> None:
        payload = (
            b"%PDF-1.4\n<</CreationDate (D:20260815184757+00'00')\n"
            b"/ModDate (D:20260815184758+00'00')>>\n"
        )
        expected = (
            b"%PDF-1.4\n<</CreationDate (D:19700101000000+00'00')\n"
            b"/ModDate (D:19700101000000+00'00')>>\n"
        )
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "figure.pdf"
            target.write_bytes(payload)
            common.normalize_pdf_metadata(target)
            self.assertEqual(target.read_bytes(), expected)
            common.normalize_pdf_metadata(target)
            self.assertEqual(target.read_bytes(), expected)

    def test_non_metadata_date_text_is_unchanged(self) -> None:
        payload = b"stream D:20260815184757+00'00' endstream"
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "figure.pdf"
            target.write_bytes(payload)
            common.normalize_pdf_metadata(target)
            self.assertEqual(target.read_bytes(), payload)


class ResearchRootTest(unittest.TestCase):
    @staticmethod
    def checkout(directory: str) -> Path:
        (Path(directory) / "docs" / "experiments").mkdir(parents=True)
        return Path(directory)

    def test_explicit_path_takes_precedence_over_environment(self) -> None:
        with tempfile.TemporaryDirectory() as first, tempfile.TemporaryDirectory() as second:
            explicit, configured = self.checkout(first), self.checkout(second)
            with mock.patch.dict(os.environ, {common.RESEARCH_ENV: str(configured)}):
                self.assertEqual(common.research_root(explicit), explicit)
                self.assertEqual(common.research_root(), configured)

    def test_missing_checkout_is_reported(self) -> None:
        with tempfile.TemporaryDirectory() as empty:
            with self.assertRaises(FileNotFoundError):
                common.research_root(empty)


